import * as THREE from 'three';
import { PALETTE } from './shared.js';

/* =========================================================
   ATMOSPHERE — полностью переписано
   =========================================================
   Что изменилось:

   Было:
   - AmbientLight 0.8 (много рассеянного света)
   - HemisphereLight (мягкое заполнение)
   - Moon DirectionalLight (лунный свет сверху)
   - FogExp2 0.022 (лёгкий туман)
   - Нет ощущения замкнутости

   Стало:
   - AmbientLight 0.25 (минимум — тени почти чёрные)
   - HemisphereLight — ХОЛОДНОЕ небо, ТЁПЛЫЙ пол
   - НЕТ DirectionalLight — свет только от источников
   - FogExp2 0.045 (плотный — пещера)
   - Цвет фона — почти чёрный
   - Цвет тумана — тёмно-синий с фиолетовым подтоном

   Принципы:
   - Свет идёт ТОЛЬКО от фонаря, кристаллов, листьев
   - Тени глубокие, не серые
   - Воздух густой
   - Дальние объекты исчезают в тумане
   ========================================================= */

export function createAtmosphere(scene, qualityLevel = 'high') {
  const isLow = qualityLevel === 'low';
  const isMedium = qualityLevel === 'medium';

  /* ==========================================================
     1. ФОН — почти чёрный с фиолетовым подтоном
     ==========================================================
     Это цвет "неба" в пещере — то, что видно в глубине.
     В референсе это тёмно-фиолетовый.
     ========================================================== */
  scene.background = new THREE.Color(0x03050a);

  /* ==========================================================
     2. ТУМАН — ПЛОТНЫЙ, чтобы создать замкнутость
     ==========================================================
     FogExp2:
     - high: 0.045 — видно на 15-20 единиц
     - medium: 0.06 — на 10-15
     - low: 0.08 — на 5-10

     Цвет: тёмно-синий с фиолетовым подтоном.
     ========================================================== */
  const fogDensity = isLow ? 0.038 : isMedium ? 0.029 : 0.022;
  const fogColor = 0x111624;

  scene.fog = new THREE.FogExp2(fogColor, fogDensity);

  /* ==========================================================
     3. СВЕТ — минимум рассеянного, максимум от источников
     ========================================================== */

  /* --- 3.1 AMBIENT — очень слабый ---
     Почти не даёт света. Только чтобы **тени не были чёрными**.
     В пещере нет "общего света" — только от источников.
     --- */
  const ambient = new THREE.AmbientLight(0x68708a, 0.32);
  scene.add(ambient);

  /* --- 3.2 HEMISPHERE — холодное небо, тёплый пол ---
     - Сверху (sky) — холодный фиолетово-синий — отражение от кристаллов
     - Снизу (ground) — тёмный тёплый — отражение от мха
     - Intensity 0.6 — умеренно
     --- */
  const hemi = new THREE.HemisphereLight(
    0x6878a0,    // sky — холодный каменный сине-серый
    0x303526,    // ground — мшистая тень
    0.7
  );
  scene.add(hemi);

  /* --- 3.3 НЕТ DirectionalLight ---
     Убрали "лунный свет". В пещере его нет.
     Свет идёт только от локальных источников.
     --- */

  /* ==========================================================
     4. ССЫЛКИ
     ========================================================== */
  scene.userData.lights = {
    ambient,
    hemi,
  };

  /* ==========================================================
     API
     ========================================================== */
  return {
    ambient,
    hemi,

    setFogDensity(density) {
      scene.fog.density = density;
    },

    setFogColor(hex) {
      scene.fog.color.setHex(hex);
      scene.background.setHex(hex);
    },

    update() {},

    dispose() {},
  };
}
